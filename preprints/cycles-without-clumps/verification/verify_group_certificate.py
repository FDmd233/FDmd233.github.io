# Additional short, human-checkable PGL_3(F_16) word certificates.
# The group letter e denotes TdT^(-1); D,E are inverses of d,e.
identity_mat=((1,0,0),(0,1,0),(0,0,1))
dinv=matmul(matmul(d,d),matmul(d,d))
einv=matmul(matmul(fprime,fprime),matmul(fprime,fprime))
letters={'d':d,'e':fprime,'D':dinv,'E':einv}
def eval_word(word):
    m=identity_mat
    for c in word:
        m=matmul(m,letters[c])
    return m

def normalize_matrix(m):
    c=next(x for row in m for x in row if x)
    inv=power(c,14)
    return tuple(tuple(mul(x,inv) for x in row) for row in m)

def mat_P(a,b):
    return ((1^b,b,power(a,4)),(b,1^b,power(a,4)),(a,a,1))
short_words=[
    (1,4,'eeDeeddEDD'),
    (2,10,'DeDEDDeded'),
    (4,8,'edeDDee'),
    (8,4,'eddEddeed'),
]
for a,b,word in short_words:
    assert power(b,4)^b == power(a,5)
    assert normalize_matrix(eval_word(word))==normalize_matrix(mat_P(a,b))
assert normalize_matrix(eval_word('EdeDDedEDD'))==normalize_matrix(S)
